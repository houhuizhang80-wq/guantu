function mergeRoutes(base: Post[], extra: Post[], links: { from: string; path: NextPath }[]): Post[] {
  const map = new Map<string, Post>()
  for (const p of base) {
    map.set(p.id, { ...p, nextPaths: [...p.nextPaths] })
  }
  for (const p of extra) {
    if (map.has(p.id)) continue
    map.set(p.id, { ...p, nextPaths: [...p.nextPaths] })
  }
  for (const link of links) {
    const from = map.get(link.from)
    if (!from) continue
    if (from.nextPaths.some((x) => x.to === link.path.to)) continue
    from.nextPaths.push(link.path)
  }
  return Array.from(map.values()).sort((a, b) => a.rank - b.rank)
}

