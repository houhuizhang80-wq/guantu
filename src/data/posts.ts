export function chapterOf(postId: string): '乡镇篇' | '县区篇' | '市级篇' | '省级篇' | '中央篇' {
  const stage = getPost(postId).stage
  if (stage === '乡镇') return '乡镇篇'
  if (stage === '县区') return '县区篇'
  if (stage === '市级') return '市级篇'
  if (stage === '省级') return '省级篇'
  return '中央篇'
}

